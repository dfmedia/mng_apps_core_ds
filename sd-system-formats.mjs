// Style Dictionary formats for system color tokens (DEC-16).
//   iOS     -> ../mng_apps_ios_ds/Tokens/MNGSystemColors.swift
//   Android -> ../mng_apps_android_ds/tokens/MngSystemColors.kt + res/values/mng_system_colors.xml
// Majority values only; exceptions are documented in mng_apps_core_ds/docs/SYSTEM-COLORS.md (per market), not built.
// Colors that follow a brand role have no value of their own: they read the market palette (MNGBrandPalette / MngBrandPalette,
// @color/mng_brand_<role>). They are listed in tokens/<platform>/system.tokens.json under the group's $extensions.mng.follows.
import { readFileSync } from 'node:fs';

const camel = (parts) => parts.join('-').split(/[-./]/).filter(Boolean).map((w, i) => i === 0 ? w : w[0].toUpperCase() + w.slice(1)).join('');
const snake = (parts) => parts.join('_').replace(/[-./]/g, '_');
const follows = (plat) => JSON.parse(readFileSync(`tokens/${plat}/system.tokens.json`, 'utf8')).color[`${plat}-system`].$extensions.mng.follows;
const rgbTxt = (h) => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16)).join(', ') + (h.length === 9 ? `, alpha ${(parseInt(h.slice(7), 16) / 255).toFixed(2)}` : '');
const HEADER = 'Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-16). Do not edit by hand.';

// Core tokens for a platform: color.system.* (same on both) + color.system-<plat>.* (Core, per-platform value); then <plat>-system.*
function pick(dictionary, plat) {
  const T = dictionary.allTokens;
  const core = T.filter(t => t.path[0] === 'color' && (t.path[1] === 'system' || t.path[1] === `system-${plat}`));
  const own = T.filter(t => t.path[0] === 'color' && t.path[1] === `${plat}-system`);
  const all = [...core, ...own].map(t => ({ t, name: camel(t.path.slice(2)), core: core.includes(t) }));
  const seen = new Set();
  for (const x of all) { if (seen.has(x.name)) throw new Error('duplicate system color name ' + x.name); seen.add(x.name); }
  return all;
}

export function registerSystemFormats(StyleDictionary) {
  StyleDictionary.registerFormat({
    name: 'mng/swift-system',
    format: ({ dictionary }) => {
      const all = pick(dictionary, 'ios');
      const swift = (t) => {
        const ui = t.$extensions?.mng?.uikit ?? t.original?.$extensions?.mng?.uikit;
        if (ui) return `UIColor.${ui}  // not set by the app: UIKit default`;
        const h = t.$value.toLowerCase();
        const base = `UIColor(mngHex: 0x${h.slice(1, 7).toUpperCase()})`;
        return (h.length === 9 ? `${base}.withAlphaComponent(${(parseInt(h.slice(7), 16) / 255).toFixed(2)})` : base) + `  // ${h} · ${rgbTxt(h)}`;
      };
      let s = `// ${HEADER}\n// Exceptions (not built): mng_apps_core_ds/docs/SYSTEM-COLORS.md · token list: docs/SYSTEM-TOKENS.md\nimport UIKit\n\n`;
      s += '/// System colors: majority value of every themed color that is not a brand, app shell, control or button token (DEC-16).\npublic enum MNGSystemColors {\n';
      s += '    // MARK: Core (same screen element on both apps)\n';
      for (const x of all.filter(x => x.core)) s += `    /// ${x.t.$description}\n    public static let ${x.name} = ${swift(x.t)}\n`;
      s += '    // MARK: iOS only\n';
      for (const x of all.filter(x => !x.core)) s += `    /// ${x.t.$description}\n    public static let ${x.name} = ${swift(x.t)}\n`;
      s += '}\n\n/// System colors that follow the market\'s brand color (DEC-16): read them from the market palette.\npublic extension MNGBrandPalette {\n';
      for (const [n, f] of Object.entries(follows('ios'))) s += `    /// ${f.$description}\n    var ${camel([n])}: UIColor { ${f.follows} }\n`;
      return s + '}\n';
    },
  });
  StyleDictionary.registerFormat({
    name: 'mng/kotlin-system',
    format: ({ dictionary, options }) => {
      const all = pick(dictionary, 'android');
      const kt = (t) => { const h = t.$value.toLowerCase(); const a = h.length === 9 ? h.slice(7).toUpperCase() : 'FF'; return `Color(0x${a}${h.slice(1, 7).toUpperCase()})  // ${h} · ${rgbTxt(h)}`; };
      let s = `// ${HEADER}\n// Exceptions (not built): mng_apps_core_ds/docs/SYSTEM-COLORS.md · token list: docs/SYSTEM-TOKENS.md\npackage ${options.packageName}\n\nimport androidx.compose.ui.graphics.Color\n\n`;
      s += '/** System colors: majority value of every themed color that is not a brand, app shell, control or button token (DEC-16). */\nobject MngSystemColors {\n';
      s += '    // Core (same screen element on both apps)\n';
      for (const x of all.filter(x => x.core)) s += `    /** ${x.t.$description} */\n    val ${x.name} = ${kt(x.t)}\n`;
      s += '    // Android only\n';
      for (const x of all.filter(x => !x.core)) s += `    /** ${x.t.$description} */\n    val ${x.name} = ${kt(x.t)}\n`;
      s += '}\n\n// System colors that follow the market\'s brand color (DEC-16): read them from the market palette.\n';
      for (const [n, f] of Object.entries(follows('android'))) s += `/** ${f.$description} */\nval MngBrandPalette.${camel([n])}: Color get() = ${f.follows}\n`;
      return s;
    },
  });
  StyleDictionary.registerFormat({
    name: 'mng/android-system-xml',
    format: ({ dictionary }) => {
      const all = pick(dictionary, 'android');
      const xml = (t) => { const h = t.$value.toLowerCase(); const a = h.length === 9 ? h.slice(7).toUpperCase() : 'FF'; return `#${a}${h.slice(1, 7).toUpperCase()}`; };
      const esc = (d) => d.replace(/--/g, '-').replace(/`/g, '');
      let s = `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${HEADER} Exceptions (not built): mng_apps_core_ds/docs/SYSTEM-COLORS.md. Brand-following colors alias the flavor's @color/mng_brand_<role>. -->\n<resources>\n`;
      for (const x of all) s += `    <color name="mng_system_${snake(x.t.path.slice(2))}">${xml(x.t)}</color> <!-- ${esc(x.t.$description)} -->\n`;
      for (const [n, f] of Object.entries(follows('android'))) s += `    <color name="mng_system_${snake([n])}">@color/mng_brand_${f.follows}</color> <!-- ${esc(f.$description)} -->\n`;
      return s + '</resources>\n';
    },
  });
}
