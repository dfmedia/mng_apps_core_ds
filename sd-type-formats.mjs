// Style Dictionary formats for the text styles (DEC-09). Imported by style-dictionary.config.mjs.
//   iOS     -> ../mng_apps_ios_ds/Tokens/MNGTypeStyles.swift   (UIFont by production PostScript name; legacy-template values)
//   Android -> ../mng_apps_android_ds/tokens/MngTypeStyles.kt  (asset file names for TypefaceCache, sizes in sp; View-based UI)
const HEADER = '// Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-09). Do not edit by hand.\n// Spec: mng_apps_core_ds/docs/TYPE-STYLES.md\n';
const px = (v) => parseFloat(String(v).replace('px', ''));
const ext = (t) => t.$extensions.mng;
const upperSnake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
const byCode = (a, b) => ext(a).code.localeCompare(ext(b).code);

export function registerTypeFormats(StyleDictionary) {
  StyleDictionary.registerFormat({
    name: 'mng/swift-type',
    format: ({ dictionary }) => {
      const T = dictionary.allTokens.filter(t => t.path[0] === 'type' && t.path[1] === 'ios').sort(byCode);
      const spec = (ps, size) => `MNGTextStyleSpec(postscript: "${ps}", size: ${size})`;
      let s = HEADER + 'import UIKit\n\n';
      s += '/// One production font: PostScript name and size in pt.\npublic struct MNGTextStyleSpec: Equatable {\n    public let postscript: String\n    public let size: CGFloat\n}\n\n';
      s += '/// Every iOS text style as shipped (TroncKit Style.json + TroncAppThemeable), majority-market values.\n';
      s += '/// Legacy-template markets (BS, DP, HC, MC, OS, SS, VP) use `legacySpec` where it differs.\n';
      s += 'public enum MNGTextStyle: String, CaseIterable {\n';
      s += T.map(t => `    /// ${t.$description}\n    case ${ext(t).code}`).join('\n') + '\n\n';
      s += '    /// Standard-template value.\n    public var spec: MNGTextStyleSpec {\n        switch self {\n';
      s += T.map(t => `        case .${ext(t).code}: return ${spec(ext(t).postscript, px(t.$value.fontSize))}`).join('\n') + '\n        }\n    }\n\n';
      s += '    /// Legacy-template value, or nil when the legacy template uses the standard value.\n    public var legacySpec: MNGTextStyleSpec? {\n        switch self {\n';
      for (const t of T) if (ext(t).legacy) s += `        case .${ext(t).code}: return ${spec(ext(t).legacy.postscript, ext(t).legacy.fontSize)}\n`;
      s += '        default: return nil\n        }\n    }\n\n';
      s += '    /// Styles that exist only in the legacy template.\n    public var isLegacyOnly: Bool {\n        switch self {\n';
      const lo = T.filter(t => ext(t).legacyOnly).map(t => '.' + ext(t).code);
      s += (lo.length ? `        case ${lo.join(', ')}: return true\n` : '') + '        default: return false\n        }\n    }\n\n';
      s += '    /// The production font. Falls back to the system font at the same size (never a different size).\n';
      s += '    public func font(legacyTemplate: Bool = false) -> UIFont {\n        let s = (legacyTemplate ? legacySpec : nil) ?? spec\n        return UIFont(name: s.postscript, size: s.size) ?? .systemFont(ofSize: s.size)\n    }\n\n';
      s += '    /// The production font for a market code, e.g. "TDP" (legacy markets get their legacy values).\n';
      s += '    public func font(forMarket market: String) -> UIFont { font(legacyTemplate: MNGButtonTokens.isLegacy(market)) }\n}\n';
      return s;
    },
  });

  StyleDictionary.registerFormat({
    name: 'mng/kotlin-type',
    format: ({ dictionary, options }) => {
      const T = dictionary.allTokens.filter(t => t.path[0] === 'type' && t.path[1] === 'android').sort(byCode);
      let s = HEADER + `package ${options.packageName}\n\n`;
      s += '/**\n * One Android text style as shipped (android-tribpub styles and dimens).\n';
      s += ' * [assetFile] is the font file the app loads from assets through TypefaceCache; null with [systemFont] = the system font (Roboto);\n';
      s += ' * null without [systemFont] = the font is not in the export (MISSING-ASSETS 4.4).\n */\n';
      s += 'data class MngTextStyle(\n    val assetFile: String?,\n    val systemFont: Boolean,\n    val bold: Boolean,\n    val sizeSp: Float,\n    val lineSpacingMultiplier: Float = 1f,\n    val letterSpacingEm: Float = 0f,\n    val allCaps: Boolean = false,\n)\n\n';
      s += '/** Every Android text style, majority-market values. Per-market font exceptions are in the token notes. */\nobject MngTypeStyles {\n';
      for (const t of T) {
        const e = ext(t), v = t.$value;
        const args = [
          `assetFile = ${e.asset ? `"${e.asset}"` : 'null'}`,
          `systemFont = ${e.system}`,
          `bold = ${v.fontWeight >= 600}`,
          `sizeSp = ${px(v.fontSize)}f`,
          v.lineHeight ? `lineSpacingMultiplier = ${v.lineHeight}f` : null,
          v.letterSpacing ? `letterSpacingEm = ${parseFloat(v.letterSpacing)}f` : null,
          e.uppercase ? 'allCaps = true' : null,
        ].filter(Boolean).join(', ');
        s += `    /** ${t.$description}${e.fontKnown ? '' : ' (font not in the export)'} */\n    val ${upperSnake(e.code)} = MngTextStyle(${args})\n`;
      }
      s += '}\n';
      return s;
    },
  });
}
