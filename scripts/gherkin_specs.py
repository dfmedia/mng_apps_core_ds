def _flat(o, p=''):
    for k, v in o.items():
        if k.startswith('$'): continue
        if isinstance(v, dict) and '$value' in v: yield p + k, v['$value']
        elif isinstance(v, dict): yield from _flat(v, p + k + '.')


TOK = {plat: dict(_flat(json.load(open(f'tokens/{plat}/scale.tokens.json')))) for plat in ('ios', 'android')}
def t(plat, key):
    v = TOK[plat][f'component.{plat}.{key}']; return v.replace('px', ' pt' if plat == 'ios' else 'dp')


def _lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]; c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
ratio = lambda a, b='#ffffff': round((max(_lum(a), _lum(b)) + 0.05) / (min(_lum(a), _lum(b)) + 0.05), 2)
h6 = lambda v: '#' + v.lstrip('#')[-6:].upper()
def akey(k):
    i = AM['tokens'].index(k); return {m['code']: h6(m['values'][i]) for m in AM['markets']}


def outline(title, given, when, then, header, rows, depth=2):
    L = [IND * depth + f'Scenario Outline: {title}', IND * (depth + 1) + f'Given {given}']
    if when: L.append(IND * (depth + 1) + f'When {when}')
    L += [IND * (depth + 1) + ('Then ' if i == 0 else 'And ') + s for i, s in enumerate(then)]
    return L + ['', IND * (depth + 1) + 'Examples:'] + _table(header, rows, depth + 2) + ['']


