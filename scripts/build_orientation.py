"""Screen orientation, as shipped (documented, nothing new).
Usage: python3 scripts/build_orientation.py
Reads  data/source/orientation.json (copied from both style guides, project/4-layout.md, 2026-11-10)
Writes data/orientation.json, docs/ORIENTATION.md
Ownership: a device class is Core when both apps ship the same orientation rule; otherwise Differs.
"""
import json
S = json.load(open('data/source/orientation.json'))
rows = []
for key, label in (('phone', 'Phone'), ('tablet', 'Tablet'), ('foldable', 'Foldable')):
    i, a = S['ios'][key], S['android'][key]
    rows.append({'device_class': label, 'ios': i, 'android': a,
                 'bucket': 'Core' if i['orientation'] == a['orientation'] else 'Differs'})
out = {'generated_by': 'scripts/build_orientation.py', 'source': {'ios': S['ios']['source'], 'android': S['android']['source']},
       'rule': 'Documented as shipped. No tokens: orientation is app configuration, not a design value.',
       'summary': 'Both apps: phones portrait only, tablets every orientation, no foldable support. The only difference is how the phone lock is set (iOS app delegate, Android from code per screen).',
       'rows': rows}
json.dump(out, open('data/orientation.json', 'w'), indent=1, ensure_ascii=False)
L = ['# Orientation (as shipped)', '', 'Generated by `scripts/build_orientation.py` from `data/source/orientation.json`. Do not edit by hand.', '',
     out['summary'], '', f"Sources: iOS {out['source']['ios']}; Android {out['source']['android']}.", '',
     '| Device class | iOS | Android | Ownership |', '|---|---|---|---|']
for r in rows:
    f = lambda p: f"**{p['orientation']}**{' · ' + p['device'] if p.get('device') else ''}. {p['how']}. Source: `{p['evidence']}`"
    L.append(f"| {r['device_class']} | {f(r['ios'])} | {f(r['android'])} | {r['bucket']} |")
open('docs/ORIENTATION.md', 'w').write('\n'.join(L) + '\n')
print(' · '.join(f"{r['device_class']}: {r['bucket']}" for r in rows))
