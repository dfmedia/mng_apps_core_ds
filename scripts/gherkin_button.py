"""Button behavior as Gherkin (pilot, 2026-11-24): states, platform differences, per-market link colors and contrast.
Called by scripts/build_button_tokens.py after it writes data/button-spec.json.
Reads:  data/button-spec.json, data/source/button-shipped.json (link font exceptions)
Writes: docs/components/button.feature; returns the same text for the Behavior section of docs/components/BUTTON.md
Scenarios describe the apps as they ship (DEC-09). Markets that miss a target are tagged @known-issue with the
IMPROVEMENTS ID, beside the target, never instead of it (rule 1).
"""
import json
from collections import defaultdict

IND = '  '


def _table(header, rows, depth=3):
    w = [max(len(str(x)) for x in col) for col in zip(header, *rows)]
    line = lambda r: IND * depth + '| ' + ' | '.join(str(x).ljust(n) for x, n in zip(r, w)) + ' |'
    return [line(header)] + [line(r) for r in rows]


def _group(rows, key, val):
    g = defaultdict(list)
    for r in rows:
        g[val(r)].append(r[key])
    return sorted(g.items(), key=lambda kv: -len(kv[1]))


def _markets(codes, total):
    # 'every other market' only for a true remainder (more than half of the markets); otherwise list them
    return f'every other market ({len(codes)})' if len(codes) * 2 > total else ', '.join(sorted(codes))


def build(spec, ship):
    P, D, rows = spec['platform'], spec['disabled'], spec['markets']
    ios, andr = P['ios'], P['android']
    lf = ship['text_link']['ios']['font']
    L = ['# Generated by scripts/gherkin_button.py from data/button-spec.json. Do not edit by hand.',
         '# As shipped (DEC-09). @known-issue = a market misses the target today; the fix is proposed in docs/IMPROVEMENTS.md.',
         '', 'Feature: Primary button and text link',
         IND + 'The paywall purchase button and its log-in link: one Core component, platform values kept as shipped (DEC-07, DEC-22, DEC-24).', '',
         IND + 'Rule: The primary button looks the same in every market except its fill', '',
         IND * 2 + 'Scenario Outline: Enabled primary button on <platform>',
         IND * 3 + 'Given the <platform> app for any market',
         IND * 3 + 'When a primary button is enabled',
         IND * 3 + "Then its fill is the market's action color",
         IND * 3 + 'And its label is white, <label>',
         IND * 3 + 'And it is <height> tall with corner radius <radius>',
         IND * 3 + 'And it has <border>', '',
         IND * 3 + 'Examples:']
    L += _table(['platform', 'label', 'height', 'radius', 'border'], [
        ['iOS', 'Open Sans Bold 14, always uppercase', f"{ios['height']} pt", f"{ios['radius']} pt", f"a {ios['border']} pt border in the fill color"],
        ['Android', 'Roboto Medium 14sp, uppercase', f"{andr['height']} dp", f"{andr['radius']} dp", 'no border']], 4)
    L += ['', IND * 2 + 'Scenario Outline: Pressed primary button on <platform>',
          IND * 3 + 'Given an enabled primary button in the <platform> app',
          IND * 3 + 'When the reader presses it',
          IND * 3 + 'Then <feedback>',
          IND * 3 + 'And no custom pressed color is used', '',
          IND * 3 + 'Examples:']
    L += _table(['platform', 'feedback'], [['iOS', 'the title fades and the fill stays the same (UIKit system)'],
                                           ['Android', 'the Material ripple plays over the fill']], 4)
    L += ['', IND * 2 + 'Scenario: Disabled primary button',
          IND * 3 + 'Given a primary button is disabled',
          IND * 3 + f"Then its fill is {D['fill']} and its label is {D['label']} ({D['contrast']}:1)",
          IND * 3 + 'And it does not respond to taps',
          IND * 3 + '# Disabled controls are exempt from WCAG 1.4.3. Android ships this on Continue; new on iOS.', '',
          IND * 2 + 'Scenario Outline: Purchase in progress on <platform>',
          IND * 3 + 'Given the reader tapped the primary button',
          IND * 3 + 'When the purchase is in progress',
          IND * 3 + 'Then the button shows no spinner of its own',
          IND * 3 + 'And <loading> covers the screen', '',
          IND * 3 + 'Examples:']
    L += _table(['platform', 'loading'], [['iOS', 'a full-screen overlay'], ['Android', 'a full-screen progress dialog']], 4)

    # contrast of the white label
    passing = [r['code'] for r in rows if r['label_pass']]
    L += ['', IND + 'Rule: White label text on the action fill has at least 4.5:1 contrast', '',
          IND * 2 + 'Scenario Outline: White label in <markets>',
          IND * 3 + 'Given the app for <markets> with action <action>',
          IND * 3 + 'When a primary button is enabled',
          IND * 3 + 'Then white label text has <ratio>:1 contrast, at least 4.5:1', '',
          IND * 3 + f'Examples: passing ({len(passing)} of {len(rows)} markets)']
    ok = [r for r in rows if r['label_pass']]
    L += _table(['markets', 'action', 'ratio'], [[_markets(cs, len(rows)), a, rt] for (a, rt), cs in sorted(_group(ok, 'code', lambda r: (r['action'], r['label_contrast'])), key=lambda kv: kv[0][1])], 4)
    L += ['',
          IND * 3 + '@known-issue @CLR-04',
          IND * 3 + 'Examples: failing today (suggested action in docs/IMPROVEMENTS.md CLR-04)']
    L += _table(['markets', 'action', 'ratio'], [[_markets(cs, len(rows)), a, rt] for (a, rt), cs in sorted(_group([r for r in rows if not r['label_pass']], 'code', lambda r: (r['action'], r['label_contrast'])), key=lambda kv: kv[0][1])], 4)

    # text link
    L += ['', IND + 'Rule: The paywall log-in link is underlined text in the market link color', '',
          IND * 2 + 'Scenario Outline: Log-in link on iOS',
          IND * 3 + 'Given the iOS app for <markets>',
          IND * 3 + 'When the meter paywall shows "Already a Subscriber? Log in to your … account" (market name in the sentence)',
          IND * 3 + f"Then the whole sentence is underlined, Open Sans Regular <size> pt, in <color>",
          IND * 3 + 'And it sits centered below the purchase button', '',
          IND * 3 + 'Examples:']
    size = {c: int(s) for s, cs in lf['exceptions'].items() for c in cs}
    g = _group(rows, 'code', lambda r: (r['ios_link'], size.get(r['code'], lf['size'])))
    L += _table(['markets', 'color', 'size'], [[_markets(cs, len(rows)), c, s] for (c, s), cs in g], 4)
    L += ['', IND * 2 + 'Scenario Outline: Log-in link on Android',
          IND * 3 + 'Given the Android app for <markets>',
          IND * 3 + 'When the paywall shows the log-in link',
          IND * 3 + 'Then it is underlined system sans 16sp text in <color> on the white paywall',
          IND * 3 + '# color resource link (DEC-24); Paywall_LoginButton_Text is not used by any code', '',
          IND * 3 + 'Examples:']
    g = _group([r for r in rows if not r['provisional_market']], 'code', lambda r: r['android_link'])
    L += _table(['markets', 'color'], [[_markets(cs, len(rows) - 1), c] for c, cs in g], 4)

    for plat, k in (('iOS', 'ios'), ('Android', 'android')):
        rs = [r for r in rows if not (plat == 'Android' and r['provisional_market'])]
        ok = [r for r in rs if r[f'{k}_link_pass']]; bad = [r for r in rs if not r[f'{k}_link_pass']]
        L += ['', IND * 2 + f'Scenario Outline: {plat} log-in link contrast in <markets>',
              IND * 3 + f'Given the {plat} app for <markets> with link color <color>',
              IND * 3 + 'Then the link has <ratio>:1 contrast on white, at least 4.5:1', '',
              IND * 3 + f'Examples: passing ({len(ok)} markets)']
        L += _table(['markets', 'color', 'ratio'], [[_markets(cs, len(rs)), c, rt] for (c, rt), cs in _group(ok, 'code', lambda r: (r[f'{k}_link'], r[f'{k}_link_contrast']))], 4)
        L += ['', IND * 3 + '@known-issue @CLR-04', IND * 3 + f'Examples: failing today ({len(bad)} markets)']
        L += _table(['markets', 'color', 'ratio'], [[_markets(cs, len(rs)), c, rt] for (c, rt), cs in _group(bad, 'code', lambda r: (r[f'{k}_link'], r[f'{k}_link_contrast']))], 4)
    text = '\n'.join(L) + '\n'
    open('docs/components/button.feature', 'w').write(text)
    return text


if __name__ == '__main__':
    build(json.load(open('data/button-spec.json')), json.load(open('data/source/button-shipped.json')))
    print('docs/components/button.feature')
