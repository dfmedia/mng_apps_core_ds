"""Scales step 2: layout spacing and touch-target tokens from the shipped values (DEC-11).
Usage: python3 scripts/build_scale_tokens.py   (after compare_scales.py; then `npm run build`)
Reads:  data/scale-comparison.json
Writes: tokens/core/scale.tokens.json      space.* / grid.*      values both apps ship the same
        tokens/ios/scale.tokens.json       space.ios.* / size.ios.*
        tokens/android/scale.tokens.json   space.android.* / size.android.*
Component-specific radii and sizes (Continue, savings label, player controls …) are NOT tokens: per DEC-09 they are used
as raw production values when that component is built. Breakpoints wait on LAY-01 (iOS has two sets; Android uses inches).
"""
import json
C = {r['role']: r for r in json.load(open('data/scale-comparison.json'))['roles']}
num = lambda t: float(str(t['value']).split()[0].replace('px', ''))

def dim(t, desc, platform):
    return {'$value': f"{num(t):g}px", '$type': 'dimension', '$description': desc,
            '$extensions': {'mng': {'source': t['name'], 'usage': t['usage'], 'platform': platform}}}

# role -> (token path, description)
CORE = {'Section-front cell margin': ('space.cell.margin', 'Outer margin of a section-front cell (both apps 16)'),
        'Section-front cell gap': ('space.cell.gap', 'Space between elements inside a section-front cell (both apps 8)'),
        'Article side margin, phone': ('space.article.side', 'Article side margin on phones (both apps 16; iOS grows with width, Android 30 landscape / 75 tablet)')}
IOS = {'Article top margin, phone': ('space.ios.article.top', 'Article card top margin, iPhone'),
       'Article top margin, tablet': ('space.ios.article.top-tablet', 'Article card top margin, iPad'),
       'Minimum touch target': ('size.ios.touch-min', 'Apple minimum touch target (not enforced in the app today)')}
AND = {'Article side margin, landscape': ('space.android.article.side-landscape', 'Article side padding, phone landscape'),
       'Article side margin, tablet': ('space.android.article.side-tablet', 'Article side padding at sw600dp and up'),
       'Minimum touch target': ('size.android.touch-min', 'Android minimum touch target (not enforced in the app today)')}

def put(tree, path, tok):
    *head, last = path.split('.')
    for p in head: tree = tree.setdefault(p, {})
    tree[last] = tok

core, ios, andr = {}, {}, {}
for role, (path, desc) in CORE.items():
    r = C[role]; assert r['match'] == 'same', role
    put(core, path, dim(r['ios'], desc, 'core'))
put(core, 'grid.columns', {'$value': int(num(C['Section-front grid columns']['ios'])), '$type': 'number',
                           '$description': 'Section-front items are sized in twelfths (both apps)', '$extensions': {'mng': {'platform': 'core'}}})
for role, (path, desc) in IOS.items(): put(ios, path, dim(C[role]['ios'], desc, 'ios'))
for role, (path, desc) in AND.items(): put(andr, path, dim(C[role]['android'], desc, 'android'))

meta = {'$description': 'Generated by scripts/build_scale_tokens.py (DEC-11). Production values. Do not edit by hand.'}
for f, t in (('tokens/core/scale.tokens.json', core), ('tokens/ios/scale.tokens.json', ios), ('tokens/android/scale.tokens.json', andr)):
    json.dump({**meta, **t}, open(f, 'w'), indent=1, ensure_ascii=False)
print('core', len(CORE) + 1, 'ios', len(IOS), 'android', len(AND))
