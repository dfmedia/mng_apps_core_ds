"""Per-market font exceptions, as shipped (DEC-09: fonts per platform; exceptions documented, not built).
Usage: python3 scripts/build_font_exceptions.py
Reads  data/source/markets.json (iOS, TroncKit @ e30ad2585: markets[].fonts = the 5 AppThemeable fonts)
       data/source/android-markets.json (Android, android-tribpub @ 1cfb069a6: fontKeys[i] -> markets[].fonts[i], asset file per key)
Writes data/type-font-exceptions.json, docs/TYPE-FONT-EXCEPTIONS.md
The majority value per key is what the text styles and tokens use (docs/TYPE-STYLES.md). Every other market is listed here.
iOS legacy-template markets (BS, DP, HC, MC, OS, SS, VP) also differ in Style.json label fonts: docs/LEGACY-TEMPLATE.md (DEC-10).
"""
import json, collections

I = json.load(open('data/source/markets.json')); A = json.load(open('data/source/android-markets.json'))
NAMES = {m['code']: m['name'] for m in I['markets']} | {m['code']: m['name'] for m in A['markets']}

def by_key(keys, value_of, markets):
    rows = []
    for k in keys:
        c = collections.Counter(value_of(m, k) for m in markets)
        maj, n = c.most_common(1)[0]
        exc = {}
        for m in markets:
            v = value_of(m, k)
            if v != maj: exc.setdefault(v, []).append(m['code'])
        rows.append({'key': k, 'majority': maj, 'majority_markets': n, 'exceptions': [{'value': v, 'markets': sorted(ms)} for v, ms in sorted(exc.items())]})
    return rows

# iOS: font name + size per AppThemeable key
ios_keys = list(I['markets'][0]['fonts'])
ios = by_key(ios_keys, lambda m, k: f"{m['fonts'][k]['font']} {m['fonts'][k]['size']:g}", I['markets'])
# Android: font asset file per font key
ak = A['fontKeys']
andr = by_key(ak, lambda m, k: m['fonts'][ak.index(k)], A['markets'])

def per_market(rows):
    """market -> list of {from, to, keys}: which majority font each market swaps for which, and on which keys."""
    out = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in rows:
        for e in r['exceptions']:
            for mk in e['markets']: out[mk][(r['majority'], e['value'])].append(r['key'])
    res = []
    for mk, swaps in out.items():
        res.append({'market': mk, 'name': NAMES.get(mk, mk), 'keys': sum(len(v) for v in swaps.values()),
                    'swaps': sorted([{'from': a, 'to': b, 'keys': ks} for (a, b), ks in swaps.items()], key=lambda s: -len(s['keys']))})
    return sorted(res, key=lambda r: (-r['keys'], r['market']))

out = {'generated_by': 'scripts/build_font_exceptions.py',
       'source': {'ios': 'TroncKit @ e30ad2585 (data/source/markets.json, AppThemeable fonts)', 'android': 'android-tribpub @ 1cfb069a6 (data/source/android-markets.json, fontKeys)'},
       'rule': 'DEC-09: text styles use the majority font per key; the markets below ship something else. Documented, not built (DEC-14 majority rule). Future: IMPROVEMENTS TYPE-05.',
       'ios': {'keys': len(ios_keys), 'keys_with_exceptions': sum(bool(r['exceptions']) for r in ios), 'by_key': ios, 'by_market': per_market(ios),
               'legacy_template': 'BS, DP, HC, MC, OS, SS, VP also use the legacy Style.json template (label fonts differ): docs/LEGACY-TEMPLATE.md (DEC-10)'},
       'android': {'keys': len(ak), 'keys_with_exceptions': sum(bool(r['exceptions']) for r in andr), 'by_key': andr, 'by_market': per_market(andr)}}
json.dump(out, open('data/type-font-exceptions.json', 'w'), indent=1, ensure_ascii=False)

L = ['# Per-market font exceptions (as shipped)', '', 'Generated by `scripts/build_font_exceptions.py`. Do not edit by hand.', '',
     out['rule'], '', f"Sources: iOS {out['source']['ios']}; Android {out['source']['android']}.", '']
for plat, label in (('ios', 'iOS'), ('android', 'Android')):
    P = out[plat]
    L += [f'## {label}: by market', '', f"{P['keys_with_exceptions']} of {P['keys']} font keys differ in at least one market." + (f" {P['legacy_template']}." if plat == 'ios' else ''), '',
          '| Market | Keys that differ | Majority font → this market | On keys |', '|---|---|---|---|']
    for r in P['by_market']:
        for i, s in enumerate(r['swaps']):
            L.append(f"| {r['market'] + ' ' + r['name'] if i == 0 else ''} | {r['keys'] if i == 0 else ''} | `{s['from']}` → `{s['to']}` | {len(s['keys'])}: {', '.join(s['keys'][:8])}{' …' if len(s['keys']) > 8 else ''} |")
    L += ['', f'## {label}: by font key', '', '| Key | Majority (markets) | Exceptions |', '|---|---|---|']
    for r in P['by_key']:
        if r['exceptions']:
            L.append(f"| `{r['key']}` | `{r['majority']}` ({r['majority_markets']}) | " + '; '.join(f"`{e['value']}`: {', '.join(e['markets'])}" for e in r['exceptions']) + ' |')
    L.append('')
open('docs/TYPE-FONT-EXCEPTIONS.md', 'w').write('\n'.join(L))
print('iOS', out['ios']['keys_with_exceptions'], '/', out['ios']['keys'], 'keys,', len(out['ios']['by_market']), 'markets; Android',
      out['android']['keys_with_exceptions'], '/', out['android']['keys'], 'keys,', len(out['android']['by_market']), 'markets')
