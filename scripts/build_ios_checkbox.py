"""iOS Your News checkbox, as shipped (image sets, not a drawn control).
Usage: python3 scripts/build_ios_checkbox.py
Reads  data/source/ios-assets/checkbox/*.png (copied 2026-11-10 from the iOS style guide's asset store,
       https://claude.ai/artifact/V364juyHFU3STfVZ6EgjMc, groups Checkmark-selected and Uncheck; TroncKit Assets.xcassets @3x)
       data/source/markets.json (market codes)
Writes data/ios-checkbox.json, docs/components/CHECKBOX-IOS.md
Market mapping from the iOS guide (Controls): BS, HC, MC, NYDN, OS, SS and VP have their own images, DP uses VP's,
every other market uses the generic Checked / Unchecked. Control size: component.ios checkbox/size 30 pt (DEC-12).
"""
import json, hashlib, struct, os
SRC = 'data/source/ios-assets/checkbox'
I = json.load(open('data/source/markets.json'))
codes = sorted(m['code'] for m in I['markets']); names = {m['code']: m['name'] for m in I['markets']}
SETS = [  # set name, checked file, unchecked file, markets (from the guide)
    ('Generic', 'Checked.png', 'Unchecked.png', None),
    ('BS', 'Checkmark-BS.png', 'Uncheck-BS.png', ['BS']),
    ('HC', 'Checkmark-Hart.png', 'Uncheck-Hart.png', ['HC']),
    ('MC', 'Checkmark-MC.png', 'Uncheck-MC.png', ['MC']),
    ('NYDN', 'Checkmark-NYDN.png', 'Uncheck-NYDN.png', ['NYDN']),
    ('OS', 'Checkmark-OS.png', 'Uncheck-OS.png', ['OS']),
    ('SS', 'Checkmark-SS.png', 'Uncheck-SS.png', ['SS']),
    ('VP', 'Checkmark-VP.png', 'Uncheck-VP.png', ['VP', 'DP']),
]
own = {m for s in SETS if s[3] for m in s[3]}
def info(f):
    b = open(os.path.join(SRC, f), 'rb').read(); w, h = struct.unpack('>II', b[16:24])
    return {'file': f, 'px': [w, h], 'pt': [w / 3, h / 3], 'sha256': hashlib.sha256(b).hexdigest(), 'bytes': len(b)}
sets = [{'set': n, 'checked': info(c), 'unchecked': info(u), 'markets': ms or [c2 for c2 in codes if c2 not in own]} for n, c, u, ms in SETS]
used = {s[1] for s in SETS} | {s[2] for s in SETS}
extra = [info(f) for f in sorted(os.listdir(SRC)) if f.endswith('.png') and f not in used]
out = {'generated_by': 'scripts/build_ios_checkbox.py', 'source': 'iOS style guide asset store (TroncKit @ e30ad2585, Assets.xcassets @3x), copied 2026-11-10',
       'control_size_pt': 30, 'control_size_token': 'Components · iOS › checkbox/size (component.ios checkbox size, DEC-12)',
       'image_placement': 'unknown, ask Apps team (MISSING-ASSETS 5.7): drawn centered at natural size (17 × 18 pt) inside the 30 × 30 control',
       'sets': sets, 'not_mapped': [dict(e, note='in the asset catalog; which markets use it is not stated in the guide') for e in extra]}
json.dump(out, open('data/ios-checkbox.json', 'w'), indent=1)
L = ['# Checkbox (iOS, as shipped)', '', 'Generated by `scripts/build_ios_checkbox.py`. Do not edit by hand.', '',
     'iOS draws the Your News topic checkbox with images, one set per market group, not a tinted control. Built in Figma as shipped '
     '(iOS file, Components · Controls › 02 · Checkbox, as shipped). Core recommendation (one tinted checkbox) stays in the registry; Android draws a tinted checkbox (DEC-14).', '',
     f"Control: {out['control_size_pt']} × {out['control_size_pt']} pt ({out['control_size_token']}), below the 44 pt touch target. Images: 51 × 54 px @3x = 17 × 18 pt. Placement inside the control: {out['image_placement']}.", '',
     '| Set | Checked | Unchecked | Markets |', '|---|---|---|---|']
for s in sets:
    L.append(f"| {s['set']} | `{s['checked']['file']}` | `{s['unchecked']['file']}` | {len(s['markets'])}: {', '.join(s['markets'])} |")
for e in out['not_mapped']:
    L.append(f"| — | — | `{e['file']}` | {e['note']} |")
os.makedirs('docs/components', exist_ok=True); open('docs/components/CHECKBOX-IOS.md', 'w').write('\n'.join(L) + '\n')
print(len(sets), 'sets;', len(sets[0]['markets']), 'generic markets; not mapped:', [e['file'] for e in extra])
