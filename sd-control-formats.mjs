// Style Dictionary formats for control and subscription-option tokens (DEC-14).
//   iOS     -> ../mng_apps_ios_ds/Tokens/MNGControlTokens.swift
//   Android -> ../mng_apps_android_ds/tokens/res/values/mng_controls.xml
// Per-market tints are NOT here: they follow the Core `action` color (MNGBrandPalette.action / @color/mng_brand_action).
const hex6 = (t) => t.$value.replace('#', '').slice(0, 6).toUpperCase();
const camel = (parts) => parts.join('-').split(/[-.]/).map((w, i) => i === 0 ? w : w[0].toUpperCase() + w.slice(1)).join('');
const isCtl = (t, p) => t.path[1] === `${p}-control`;

export function registerControlFormats(StyleDictionary) {
  StyleDictionary.registerFormat({
    name: 'mng/swift-controls',
    format: ({ dictionary }) => {
      const T = dictionary.allTokens.filter(t => isCtl(t, 'ios'));
      let s = '// Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-14). Do not edit by hand.\n// Exceptions (not built): mng_apps_core_ds/docs/CONTROL-EXCEPTIONS.md\nimport UIKit\n\n';
      s += '/// Control and subscription-option values (majority of markets). Per-market tints use `MNGBrandPalette.action`.\npublic enum MNGControlTokens {\n';
      for (const t of T) {
        const name = camel(t.path.slice(2));
        if (t.$type === 'color') s += `    /// ${t.$description}\n    public static let ${name} = UIColor(mngHex: 0x${hex6(t)})  // ${t.$value}\n`;
        else if (t.$type === 'typography') s += `    /// ${t.$description}\n    public static var ${name}Font: UIFont { UIFont(name: "${t.$extensions.mng.postscript}", size: ${parseFloat(t.$value.fontSize)}) ?? .boldSystemFont(ofSize: ${parseFloat(t.$value.fontSize)}) }\n`;
      }
      return s + '}\n';
    },
  });
  StyleDictionary.registerFormat({
    name: 'mng/android-controls-xml',
    format: ({ dictionary }) => {
      const T = dictionary.allTokens.filter(t => isCtl(t, 'android'));
      let s = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-14). Do not edit by hand. Per-market tints use @color/mng_brand_action. Exceptions (not built): mng_apps_core_ds/docs/CONTROL-EXCEPTIONS.md -->\n<resources>\n';
      for (const t of T) {
        const name = 'mng_' + t.path.slice(2).join('_').replace(/-/g, '_');
        if (t.$type === 'color') s += `    <color name="${name}">#FF${hex6(t)}</color> <!-- ${t.$description} -->\n`;
        else if (t.$type === 'typography') s += `    <dimen name="${name}_text_size">${parseFloat(t.$value.fontSize)}sp</dimen> <!-- ${t.$description} -->\n`;
      }
      return s + '</resources>\n';
    },
  });
}
