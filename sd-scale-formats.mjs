// Style Dictionary formats for layout spacing, touch targets, breakpoints and component metrics (DEC-11, DEC-12).
//   iOS     -> ../mng_apps_ios_ds/Tokens/MNGScaleTokens.swift
//   Android -> ../mng_apps_android_ds/tokens/res/values/mng_scale.xml
const KINDS = ['space', 'size', 'grid', 'breakpoint', 'component'];
const isScale = (t) => KINDS.includes(t.path[0]);
const px = (t) => parseFloat(String(t.$value).replace('px', ''));
const camel = (parts) => parts.map((p, i) => p.split('-').map((w, j) => (i === 0 && j === 0) ? w : w[0].toUpperCase() + w.slice(1)).join('')).join('');
const local = (t, platform) => t.path.filter(p => p !== platform);
const unit = (t) => t.$extensions?.mng?.unit;

export function registerScaleFormats(StyleDictionary) {
  StyleDictionary.registerFormat({
    name: 'mng/swift-scale',
    format: ({ dictionary }) => {
      const T = dictionary.allTokens.filter(t => isScale(t) && t.path[1] !== 'android');
      let s = '// Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-11, DEC-12). Do not edit by hand.\n// Spec: mng_apps_core_ds/docs/SCALES-COMPARISON.md\nimport CoreGraphics\n\n';
      s += '/// Layout spacing, touch targets, breakpoints (window width, pt) and component metrics, production values.\n/// Core values (no platform in the name) are the same on Android.\npublic enum MNGScale {\n';
      for (const t of T) {
        const name = camel(local(t, 'ios'));
        const v = t.$type === 'number' ? `Int = ${t.$value}` : `CGFloat = ${px(t)}`;
        s += `    /// ${t.$description}${t.path[1] === 'ios' ? ' (iOS)' : ''}\n    public static let ${name}: ${v}\n`;
      }
      return s + '}\n';
    },
  });

  StyleDictionary.registerFormat({
    name: 'mng/android-scale-xml',
    format: ({ dictionary }) => {
      const T = dictionary.allTokens.filter(t => isScale(t) && t.path[1] !== 'ios');
      let s = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-11, DEC-12). Do not edit by hand. Spec: mng_apps_core_ds/docs/SCALES-COMPARISON.md -->\n<resources>\n';
      for (const t of T) {
        const name = 'mng_' + local(t, 'android').join('_').replace(/-/g, '_');
        if (unit(t) === 'in') s += `    <item name="${name}_inches" format="float" type="dimen">${t.$value}</item> <!-- ${t.$description} -->\n`;
        else if (t.$type === 'number') s += `    <integer name="${name}">${t.$value}</integer> <!-- ${t.$description} -->\n`;
        else s += `    <dimen name="${name}">${px(t)}dp</dimen> <!-- ${t.$description} -->\n`;
      }
      return s + '</resources>\n';
    },
  });
}
