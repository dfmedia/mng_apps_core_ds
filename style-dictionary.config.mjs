// Builds platform code from the DTCG tokens in tokens/.
//   iOS     -> ../mng_apps_ios_ds/Tokens/MNGBrandColors.swift            (UIKit + SwiftUI)
//            ../mng_apps_ios_ds/Tokens/MNGButtonTokens.swift           (button pilot, DEC-07)
//            ../mng_apps_ios_ds/Tokens/MNGTypeStyles.swift             (text styles, DEC-09)
//   Android -> ../mng_apps_android_ds/tokens/MngTypeStyles.kt             (text styles, DEC-09)
//              ../mng_apps_android_ds/tokens/MngBrandColors.kt            (Jetpack Compose)
//              ../mng_apps_android_ds/tokens/res/values/mng_button.xml   (button pilot, DEC-07; View-based UI)
//              ../mng_apps_android_ds/tokens/flavors/<flavor>/res/values/mng_brand_colors.xml (one per Gradle flavor)
//              ../mng_apps_android_ds/tokens/flavors/<flavor>/res/values-v35/mng_brand_statusbar.xml (Android 15+ status bar, DEC-15)
// Colors are written from the hex bytes (0xRRGGBB), never as rounded decimals, so iOS can't drift (DSC-01).
// Run: npm run tokens && npm run build
import StyleDictionary from 'style-dictionary';
import { registerTypeFormats } from './sd-type-formats.mjs';
import { registerScaleFormats } from './sd-scale-formats.mjs';
import { registerControlFormats } from './sd-control-formats.mjs';
import { registerSystemFormats } from './sd-system-formats.mjs';

const CORE = ['navbar', 'navtext', 'tabbar', 'tabactive', 'tabinactive', 'action', 'alert', 'alerttext'];
const HEADER = '// Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-01..03). Do not edit by hand.\n';
const hex6 = (t) => t.$value.replace('#', '').slice(0, 6).toUpperCase();
const isOverride = (t) => !!t && !String(t.original?.$value ?? '').startsWith('{');   // DEC-15: hex = accepted market override, alias = follows navbar
const rgbc = (t) => { const h = hex6(t); return `rgb(${parseInt(h.slice(0,2),16)}, ${parseInt(h.slice(2,4),16)}, ${parseInt(h.slice(4,6),16)})`; };

// DEC-15: Android status-bar icon style per market { market: { icons: 'light'|'dark', icons15: ... } } (statusbar.android.<m>.*)
function sbIcons(tokens) {
  const m = {};
  for (const t of tokens) if (t.path[0] === 'statusbar' && t.path[1] === 'android') (m[t.path[2]] ??= {})[t.path[3]] = t.$value;
  return m;
}

// tokens grouped as { market: { role: token } } across the core + platform files
function byMarket(tokens) {
  const m = {};
  for (const t of tokens) {
    const [kind, group, market, role] = t.path; // color.<brand|ios|android>.<market>.<role>
    if (kind !== 'color' || !['brand', 'ios', 'android'].includes(group)) continue;
    (m[market] ??= {})[role] = t;
  }
  return Object.fromEntries(Object.entries(m).sort(([a], [b]) => a.localeCompare(b)));
}

StyleDictionary.registerFormat({
  name: 'mng/swift-palettes',
  format: ({ dictionary }) => {
    const M = byMarket(dictionary.allTokens);
    const roles = [...CORE, ...['sectiontabbar', 'sectiontabtext', 'sectiontabselected', 'sectiontabindicator']];   // section tabs: iOS only (DEC-13); header = navbar (DEC-15)
    let s = HEADER + 'import UIKit\nimport SwiftUI\n\n';
    s += '/// One market\'s brand colors. Core roles come from the Core library; `header` is iOS-only.\npublic struct MNGBrandPalette {\n';
    s += roles.map(r => `    public let ${r}: UIColor`).join('\n') + '\n    /// Accepted market override for the header band (DEC-15); nil = follows navbar.\n    public let headerOverride: UIColor?\n    /// Top bar icon tint: alias of `navtext` (DEC-13).\n    public var navicon: UIColor { navtext }\n    /// Section-front header band (iOS only): navbar, or the market override (DEC-15, Core docs/SHELL-EXCEPTIONS.md).\n    public var header: UIColor { headerOverride ?? navbar }\n    /// Alias of `action` (PLAT-04).\n    public var buy: UIColor { action }\n    /// Alias of `action` (PLAT-04).\n    public var continueButton: UIColor { action }\n}\n\n';
    s += 'public extension UIColor {\n    /// Exact sRGB color from 0xRRGGBB bytes.\n    convenience init(mngHex hex: UInt32) {\n        self.init(red: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255, blue: CGFloat(hex & 0xFF) / 255, alpha: 1)\n    }\n}\n\n';
    s += 'public extension MNGBrandPalette {\n    func color(_ keyPath: KeyPath<MNGBrandPalette, UIColor>) -> Color { Color(uiColor: self[keyPath: keyPath]) }\n}\n\n';
    s += 'public enum MNGBrandPalettes {\n';
    for (const [k, t] of Object.entries(M)) {
      const name = t.navbar?.$extensions?.mng?.market ?? k.toUpperCase();
      s += `    /// ${name} (${k.toUpperCase()})\n    public static let ${k} = MNGBrandPalette(\n`;
      s += roles.map(r => `        ${r}: UIColor(mngHex: 0x${hex6(t[r])})  /* ${t[r].$value} · ${rgbc(t[r])} */`).join(',\n');
      s += isOverride(t.header) ? `,\n        headerOverride: UIColor(mngHex: 0x${hex6(t.header)})  /* ${t.header.$value} · ${rgbc(t.header)}, DEC-15 override */\n    )\n` : ',\n        headerOverride: nil\n    )\n';
    }
    s += '\n    /// Palette for a market code, e.g. "TDP". Codes match the Gradle flavor names upper-cased.\n    public static func forMarket(_ code: String) -> MNGBrandPalette? {\n        switch code.lowercased() {\n';
    for (const k of Object.keys(M)) s += `        case "${k}": return ${k}\n`;
    s += '        default: return nil\n        }\n    }\n}\n';
    return s;
  },
});

StyleDictionary.registerFormat({
  name: 'mng/kotlin-palettes',
  format: ({ dictionary, options }) => {
    const M = byMarket(dictionary.allTokens), IC = sbIcons(dictionary.allTokens);
    const roles = [...CORE, ...['sectiontabbar', 'sectiontabtext', 'sectiontabselected', 'sectiontabindicator', 'tablabelactive', 'tablabelinactive']];   // section tabs, tab labels: Android only (DEC-13); statusbar = navbar (DEC-15)
    let s = HEADER + `package ${options.packageName}\n\nimport androidx.compose.ui.graphics.Color\n\n`;
    s += '/** One market\'s brand colors. Core roles come from the Core library; `statusbar` is Android-only. */\ndata class MngBrandPalette(\n';
    s += roles.map(r => `    val ${r}: Color`).join(',\n') + ',\n    /** Accepted market override for the status bar (DEC-15); null = follows [navbar]. Android 14 and below only. */\n    val statusbarOverride: Color? = null,\n    /** Dark status-bar icons on Android 14 and below (windowLightStatusBar on). */\n    val statusbarDarkIcons: Boolean = false,\n    /** Dark status-bar icons on Android 15+ (API 35). */\n    val statusbarDarkIcons15: Boolean = false\n) {\n    /** Top bar icon tint: alias of [navtext] (DEC-13). */\n    val navicon: Color get() = navtext\n    /** Status bar (Android only) on Android 14 and below: [navbar], or the market override (DEC-15, Core docs/SHELL-EXCEPTIONS.md). */\n    val statusbar: Color get() = statusbarOverride ?: navbar\n    /** Status bar on Android 15+ (API 35): always [navbar] (DEC-15). */\n    val statusbar15: Color get() = navbar\n    /** Status-bar color for the running Android version, e.g. statusbarFor(Build.VERSION.SDK_INT). */\n    fun statusbarFor(sdkInt: Int): Color = if (sdkInt >= 35) statusbar15 else statusbar\n    /** True = dark status-bar icons (windowLightStatusBar on) for the running Android version (DEC-15). */\n    fun statusbarDarkIconsFor(sdkInt: Int): Boolean = if (sdkInt >= 35) statusbarDarkIcons15 else statusbarDarkIcons\n    /** Alias of [action] (PLAT-04). */\n    val buy: Color get() = action\n    /** Alias of [action] (PLAT-04). */\n    val continueButton: Color get() = action\n}\n\n';
    s += 'object MngBrandPalettes {\n';
    for (const [k, t] of Object.entries(M)) {
      const name = t.navbar?.$extensions?.mng?.market ?? k.toUpperCase();
      s += `    /** ${name} (${k.toUpperCase()}) */\n    val ${k.toUpperCase()} = MngBrandPalette(\n`;
      const extra = [];
      if (isOverride(t.statusbar)) extra.push(`statusbarOverride = Color(0xFF${hex6(t.statusbar)})  // ${t.statusbar.$value} · ${rgbc(t.statusbar)}, DEC-15 override (Android 14 and below)`);
      if (IC[k]?.icons === 'dark') extra.push('statusbarDarkIcons = true');
      if (IC[k]?.icons15 === 'dark') extra.push('statusbarDarkIcons15 = true  // Android 15+: navbar with dark icons (DEC-15)');
      const lines = [...roles.map(r => [`${r} = Color(0xFF${hex6(t[r])})`, `${t[r].$value} · ${rgbc(t[r])}`]), ...extra.map(e => e.split('  // '))];
      s += lines.map(([code, note], i) => `        ${code}${i < lines.length - 1 ? ',' : ''}${note ? '  // ' + note : ''}`).join('\n') + '\n    )\n';
    }
    s += '\n    /** Palette for a market code or Gradle flavor name, e.g. "tdp". */\n    fun forMarket(code: String): MngBrandPalette? = when (code.lowercase()) {\n';
    for (const k of Object.keys(M)) s += `        "${k}" -> ${k.toUpperCase()}\n`;
    s += '        else -> null\n    }\n}\n';
    return s;
  },
});

StyleDictionary.registerFormat({
  name: 'mng/android-flavor-xml',
  format: ({ dictionary, options }) => {
    const t = byMarket(dictionary.allTokens)[options.market], ic = sbIcons(dictionary.allTokens)[options.market] ?? {};
    const roles = [...CORE, ...['sectiontabbar', 'sectiontabtext', 'sectiontabselected', 'sectiontabindicator', 'tablabelactive', 'tablabelinactive']];
    let s = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by Style Dictionary from mng_apps_core_ds/tokens (DEC-01..03). Do not edit by hand. -->\n';
    s += `<!-- ${t.navbar.$extensions.mng.market} (${options.market.toUpperCase()}) -->\n<resources>\n`;
    s += roles.map(r => `    <color name="mng_brand_${r}">#FF${hex6(t[r])}</color> <!-- ${rgbc(t[r])} -->`).join('\n');
    s += '\n    <color name="mng_brand_navicon">@color/mng_brand_navtext</color>' + (isOverride(t.statusbar) ? `\n    <color name="mng_brand_statusbar">#FF${hex6(t.statusbar)}</color> <!-- ${rgbc(t.statusbar)}, DEC-15 market override -->` : '\n    <color name="mng_brand_statusbar">@color/mng_brand_navbar</color> <!-- DEC-15 -->') + '\n    <color name="mng_brand_buy">@color/mng_brand_action</color>\n    <color name="mng_brand_continue">@color/mng_brand_action</color>\n'
      + `    <!-- Status-bar icons, Android 14 and below: true = dark icons (windowLightStatusBar). DEC-15 -->\n    <bool name="mng_brand_statusbar_dark_icons">${ic.icons === 'dark'}</bool>\n</resources>\n`;
    return s;
  },
});

